function hashIndex(parts, modulo) {
  const h = crypto.createHash("sha256").update(parts.join("|")).digest();
  return h.readUInt32BE(0) % modulo;
}

function buildPersonalizedResult(term, { scores, resolved, top }) {
  const culture = CULTURE[term.id] || {
    phenology: "",
    ritual: "",
    mirror: "",
    nuances: ["你的路径独特，节气在你身上显影为一种只属于此刻的气候。"],
  };
  const optionIds = (resolved || []).map((r) => r.optionId);
  const nuanceList = culture.nuances || ["（路径细读生成中）"];
  const nuanceIdx = hashIndex(optionIds.length ? optionIds : [term.id], nuanceList.length);
  const nuance = nuanceList[nuanceIdx];

  const secondary = top && top[1] ? getTerm(top[1].id) : null;
  let flavorTag = "独行此一候";
  let pathNote = "这一次，你的答题几乎都汇向同一候——气候干净而集中，像一天只刮一种风。";
  if (secondary && secondary.id !== term.id) {
    if (secondary.group === term.group) {
      flavorTag = `同季邻候 · ${secondary.name}`;
      pathNote = `你主显「${term.name}」，次高峰却是同季的「${secondary.name}」。像同一季节里的两阵风交替：主性格稳定，细节情绪会随路径在两者间摆动。`;
    } else {
      const gf = GROUP_FLAVOR[secondary.group] || GROUP_FLAVOR.spring;
      flavorTag = `${gf.tag} · ${secondary.name}`;
      pathNote = `${gf.note}具体来说，第二序位是「${secondary.name}」（${secondary.meaning}），它为你的「${term.name}」添了一层对照的气味。`;
    }
  }

  // 第三名微扰：再给一句短签，增强「同节气不同人」差异
  const tertiary = top && top[2] ? getTerm(top[2].id) : null;
  let microLine = "";
  if (tertiary && tertiary.id !== term.id && (!secondary || tertiary.id !== secondary.id)) {
    const micros = [
      `若再往下听一层，还能辨出「${tertiary.name}」的细响——${tertiary.meaning}。不必改写主结论，只需知道你的内在气候比单一标签更立体。`,
      `第三序位的「${tertiary.name}」像远雷或薄霜：不夺主戏，却在某些选择题里露过面。回头看那些选项，也许能对上号。`,
      `「${tertiary.name}」以很低的分站在远处，提醒你：人格从来不是单色块，而是二十四候的光谱在你身上的投影。`,
    ];
    microLine = micros[hashIndex(optionIds.concat([tertiary.id]), micros.length)];
  }

  const deepParts = [
    term.deep,
    culture.mirror ? `【物候映照】${culture.mirror}` : "",
    `【路径细读】${nuance}`,
    pathNote ? `【邻候气息】${pathNote}` : "",
    microLine ? `【谱系余音】${microLine}` : "",
  ].filter(Boolean);

  return {
    id: term.id,
    name: term.name,
    group: term.group,
    seasonLabel: term.seasonLabel,
    meaning: term.meaning,
    poem: term.poem,
    phenology: culture.phenology,
    ritual: culture.ritual,
    deep: deepParts.join("\n\n"),
    nuance,
    flavorTag,
    pathNote,
    secondary: secondary
      ? { id: secondary.id, name: secondary.name, meaning: secondary.meaning }
      : null,
    strengths: term.strengths,
    blind: term.blind,
    share: term.share,
  };
}

module.exports = { CULTURE, buildPersonalizedResult };
